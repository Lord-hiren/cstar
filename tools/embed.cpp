// embed.cpp — build-time code generator for the Pentest toolchain.
//
// Reads files byte-exactly and emits a C++ header containing them as static
// byte arrays, using the registry layout consumed by src/main.cpp:
//
//   static const unsigned char pen_file_<mangled>[] = { ... };
//   static const unsigned int pen_file_<mangled>_len = N;
//   static const struct { const char* name; const unsigned char* data;
//                         unsigned int len; } pen_embedded_files[] = { ... };
//   static const unsigned int pen_embedded_files_count = N;
//
// <mangled> is the file's basename with every non-alphanumeric character
// replaced by '_'. The entry name is the basename (the file name the data
// is later written back to).
//
// Usage: embed <output_header> <file>...

#include <cctype>
#include <cstdio>
#include <fstream>
#include <string>
#include <unordered_set>
#include <vector>

namespace {

std::string mangle(const std::string& s) {
  std::string out;
  out.reserve(s.size());
  for (unsigned char c : s) {
    out += (std::isalnum(c) || c == '_') ? static_cast<char>(c) : '_';
  }
  return out;
}

std::string base_name(const std::string& p) {
  std::size_t slash = p.rfind('/');
  return slash == std::string::npos ? p : p.substr(slash + 1);
}

std::string c_quote(const std::string& s) {
  std::string out;
  for (char c : s) {
    if (c == '\\' || c == '"') out += '\\';
    out += c;
  }
  return out;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc < 3) {
    std::fprintf(stderr, "usage: embed <output_header> <file>...\n");
    return 2;
  }
  const std::string out_path = argv[1];

  struct Entry {
    std::string name;
    std::string mangled;
    std::vector<unsigned char> data;
  };
  std::vector<Entry> entries;
  std::unordered_set<std::string> seen_mangled;

  for (int i = 2; i < argc; ++i) {
    const std::string path = argv[i];
    std::ifstream in(path, std::ios::binary);
    if (!in) {
      std::fprintf(stderr, "embed: error: cannot read '%s'\n", path.c_str());
      return 1;
    }
    Entry e;
    e.name = base_name(path);
    e.mangled = mangle(e.name);
    if (!seen_mangled.insert(e.mangled).second) {
      std::fprintf(stderr,
                   "embed: error: duplicate mangled name '%s' (from '%s')\n",
                   e.mangled.c_str(), path.c_str());
      return 1;
    }
    e.data.assign(std::istreambuf_iterator<char>(in),
                  std::istreambuf_iterator<char>());
    entries.push_back(std::move(e));
  }

  std::FILE* out = std::fopen(out_path.c_str(), "w");
  if (out == nullptr) {
    std::fprintf(stderr, "embed: error: cannot write '%s'\n", out_path.c_str());
    return 1;
  }

  std::fputs("// Generated by tools/embed.cpp — do not edit.\n", out);
  std::fputs("#pragma once\n\n", out);

  for (const Entry& e : entries) {
    std::fprintf(out, "static const unsigned char pen_file_%s[] = {",
                 e.mangled.c_str());
    if (e.data.empty()) {
      // Zero-length arrays are not portable; one sentinel byte, len stays 0.
      std::fputs("0", out);
    } else {
      for (std::size_t i = 0; i < e.data.size(); ++i) {
        if (i % 16 == 0) std::fputs("\n    ", out);
        std::fprintf(out, "0x%02x, ", e.data[i]);
      }
      std::fputs("\n", out);
    }
    std::fputs("};\n", out);
    std::fprintf(out, "static const unsigned int pen_file_%s_len = %zu;\n",
                 e.mangled.c_str(), e.data.size());
    std::fputs("\n", out);
  }

  std::fputs(
      "static const struct {\n"
      "    const char* name;\n"
      "    const unsigned char* data;\n"
      "    unsigned int len;\n"
      "} pen_embedded_files[] = {\n",
      out);
  for (const Entry& e : entries) {
    std::fprintf(out, "    {\"%s\", pen_file_%s, pen_file_%s_len},\n",
                 c_quote(e.name).c_str(), e.mangled.c_str(),
                 e.mangled.c_str());
  }
  std::fputs("};\n", out);
  std::fprintf(out, "static const unsigned int pen_embedded_files_count = %zu;\n",
               entries.size());

  if (std::fclose(out) != 0) {
    std::fprintf(stderr, "embed: error: failed writing '%s'\n",
                 out_path.c_str());
    return 1;
  }
  return 0;
}
